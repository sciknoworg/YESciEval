
from typing import TYPE_CHECKING, Optional, Type
from ..base import Parser, RubricLikertScale
from ..base.response import call_with_retries, parse_response, response_schema
from openai import OpenAI
from pydantic import BaseModel

if TYPE_CHECKING:
    from ..base import Rubric


class GPTParser(Parser):
    """
    Parser that extracts a structured evaluation result from free text with an OpenAI model.

    The extraction schema is built from the requested response model (`RubricLikertScale` by default).
    Failed API calls or invalid results are retried up to `max_attempts` times, waiting `retry_delay`
    seconds between attempts.
    """
    def __init__(self, openai_key:str, parser_model:str="gpt-4o-mini", max_attempts: int = 3, retry_delay: float = 3):
        self.client = OpenAI(api_key=openai_key)
        self.parser_model = parser_model
        self.max_attempts = max_attempts
        self.retry_delay = retry_delay

    def parse(self,
              raw_output: str,
              response_model: Type[BaseModel] = RubricLikertScale,
              rubric: Optional["Rubric"] = None) -> BaseModel:
        """
        Parse the raw model output into a validated evaluation result.

        Args:
            raw_output (str): The text generated by the model.
            response_model (Type[BaseModel]): Pydantic model of the result. Defaults to `RubricLikertScale`.
            rubric (Rubric, optional): Rubric that produced the output. When given, its `response_model`
                takes precedence over `response_model`, and its `validate_result()` is applied to the
                parsed result.

        Returns:
            BaseModel: An instance of the response model.
        """
        validator = None
        if rubric is not None:
            response_model = rubric.response_model
            validator = rubric.validate_result
        functions = [response_schema(response_model,
                                     name="evaluate_characteristic",
                                     description="Extracting the exact evaluation result from the given text.")]

        def extract() -> BaseModel:
            completion = self.client.chat.completions.create(
                model=self.parser_model,
                messages=[{"role": "user", "content": raw_output}],
                functions=functions,
                function_call={"name": "evaluate_characteristic"}
            )
            return parse_response(completion.choices[0].message.function_call.arguments,
                                  response_model,
                                  wrapper_key=rubric.name if rubric is not None else None,
                                  validator=validator)

        return call_with_retries(extract, max_attempts=self.max_attempts, retry_delay=self.retry_delay)
