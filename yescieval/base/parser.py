from abc import ABC, abstractmethod
from typing import TYPE_CHECKING, Optional, Type
from pydantic import BaseModel, Field

if TYPE_CHECKING:
    from .rubric import Rubric


class RubricLikertScale(BaseModel):
    rating: int = Field(..., ge=1, le=5, description="Rating from 1 to 5")
    rationale: str = Field(..., description="Textual explanation for the rating")


class Parser(ABC):
    """
    Abstract base class for parsing model outputs into validated evaluation results.

    The result format is a Pydantic response model; `RubricLikertScale` is the default.
    """
    @abstractmethod
    def parse(self,
              raw_output: str,
              response_model: Type[BaseModel] = RubricLikertScale,
              rubric: Optional["Rubric"] = None) -> BaseModel:
        """
        Parse the raw model output into a validated evaluation result.

        Args:
            raw_output (str): The text generated by the model.
            response_model (Type[BaseModel]): Pydantic model of the result. Defaults to `RubricLikertScale`.
            rubric (Rubric, optional): Rubric that produced the output. When given, its `response_model`
                is used and its `validate_result()` is applied to the parsed result.

        Returns:
            BaseModel: An instance of the response model.
        """
        raise NotImplementedError
